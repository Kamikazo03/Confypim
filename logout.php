<?php

declare(strict_types=1);

/**
 * ==========================================================
 * Logout
 * ==========================================================
 *
 * Finaliza la sesión del usuario autenticado y redirige
 * al formulario de Login.
 *
 * ==========================================================
 */

require_once __DIR__ . '/config/app.php';


/* ==========================================================
 * Cerrar sesión
 * ========================================================== */

cerrarSesion();


/* ==========================================================
 * Redirección
 * ========================================================== */

header(
    'Location: ' .
    BASE_URL .
    'index.php?page=login'
);

exit;